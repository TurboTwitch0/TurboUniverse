import assert from 'node:assert/strict';
import { existsSync } from 'node:fs';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright';
import { createApp } from '../server/index.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const dataDir = await mkdtemp(path.join(tmpdir(), 'turbo-ui-'));
const server = createApp({ dataDir, distDir: path.join(root, 'dist') }).listen(0, '127.0.0.1');
await new Promise(resolve => server.once('listening', resolve));
const origin = `http://127.0.0.1:${server.address().port}`;
const executablePath = process.env.CHROMIUM_PATH || (existsSync('/usr/bin/chromium') ? '/usr/bin/chromium' : undefined);
let browser;
try {
  browser = await chromium.launch({ executablePath, headless: true, args: ['--no-sandbox'] });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(origin);
  await page.getByRole('heading', { name: 'TurboHome', exact: true }).waitFor();
  assert.equal(await page.locator('.project-card').count(), 30, 'All imported projects are visible');
  await page.getByRole('button', { name: 'Add project', exact: true }).click();
  await page.getByLabel('Project name').fill('Smoke Project');
  await page.getByLabel('Project type').selectOption('app');
  await page.getByLabel('Project link').fill('https://example.com/smoke');
  await page.getByLabel('The story').fill('A real browser test of project creation.');
  await page.getByLabel('Cover image', { exact: true }).setInputFiles(path.join(root, 'public/icon-192.png'));
  await page.getByLabel('Project file', { exact: true }).setInputFiles({ name: 'smoke.html', mimeType: 'text/html', buffer: Buffer.from('<h1>Uploaded project</h1>') });
  await page.getByRole('button', { name: 'Add to the universe', exact: true }).click();
  await page.getByRole('heading', { name: 'Smoke Project', exact: true }).waitFor();
  await page.locator('.filters').getByRole('button', { name: /^Apps/ }).click();
  assert.equal(await page.locator('.project-card').count(), 3, 'App filter includes the newly uploaded app');
  await page.getByRole('searchbox', { name: 'Search projects' }).fill('Smoke Project');
  assert.equal(await page.locator('.project-card').count(), 1);
  await page.getByRole('button', { name: 'View Smoke Project', exact: true }).click();
  const downloadReady = page.waitForEvent('download');
  await page.getByRole('link', { name: 'Download project', exact: true }).click();
  assert.equal((await downloadReady).suggestedFilename(), 'smoke.html');
  await page.getByRole('button', { name: 'Remove project', exact: true }).click();
  await page.getByRole('button', { name: 'Remove', exact: true }).click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  await page.getByRole('searchbox', { name: 'Search projects' }).fill('');
  await page.locator('.filters').getByRole('button', { name: /^All worlds/ }).click();
  await page.getByRole('button', { name: 'Add project', exact: true }).click();
  await page.getByRole('button', { name: 'Bulk import', exact: true }).click();
  await page.getByLabel('Or paste project links').fill('https://example.com/one\nhttps://example.com/two');
  await page.getByRole('button', { name: 'Import projects', exact: true }).click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  await page.waitForFunction(() => document.querySelectorAll('.project-card').length === 32);
  await page.getByRole('button', { name: /The life of Turbo/ }).click();
  await page.getByRole('button', { name: 'Chapter 02' }).click();
  await page.getByRole('heading', { name: 'One idea opens another world.' }).waitFor();
  await page.keyboard.press('Escape');
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, 'Mobile layout has no horizontal overflow');
  await page.getByRole('button', { name: 'Toggle navigation' }).click();
  await page.getByRole('button', { name: 'The story', exact: true }).click();
  await page.locator('.story-heading').waitFor();
  await page.getByRole('button', { name: 'Toggle navigation' }).click();
  await page.getByRole('button', { name: /My collection/ }).click();
  const exportReady = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export project list' }).click();
  assert.equal((await exportReady).suggestedFilename(), 'turbo-universe-projects.json');
  await page.getByRole('button', { name: 'Get the app', exact: true }).click();
  await page.getByRole('heading', { name: 'Take Turbo with you.' }).waitFor();
  await page.keyboard.press('Escape');
  await page.evaluate(async () => { await navigator.serviceWorker.ready; });
  await page.reload();
  await page.waitForFunction(() => navigator.serviceWorker.controller !== null);
  await page.waitForFunction(async () => { const keys = await caches.keys(); return keys.some(key => key.startsWith('turbo-universe-projects')); });
  await context.setOffline(true);
  await page.reload();
  await page.getByRole('heading', { name: 'TurboHome', exact: true }).waitFor();
  assert.equal(await page.locator('.project-card').count(), 32, 'Offline collection uses the last successful project list');
  await page.getByRole('status').filter({ hasText: 'You’re offline' }).waitFor();
  assert.deepEqual(errors, [], 'No browser runtime errors');
  console.log('Browser smoke passed: 30 real catalog entries, uploads/downloads, filtering/search, deletion, bulk import, story, mobile navigation, export, installation UI, and offline browsing.');
} finally {
  await browser?.close();
  await new Promise(resolve => server.close(resolve));
  await rm(dataDir, { recursive: true, force: true });
}
